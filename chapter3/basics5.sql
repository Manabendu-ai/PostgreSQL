-- Arithmetic Operators
/**
  We can use our dataset to compute some statistics,
  e.g. discounted price for a product given 10% off
 */

SELECT 10 + 2; -- Add
SELECT 10 - 2; -- Sub
SELECT 10 * 2; -- Mul
SELECT 10 / 2; -- Div
SELECT 10 ^ 2; -- Power
SELECT FACTORIAL(4); -- Factorial
SELECT |/49.0; -- Square Root
SELECT ||/27.0; -- Cube Root
SELECT log10(2); -- logarithm base 10
SELECT log(2, 9) -- log 9 base 2

